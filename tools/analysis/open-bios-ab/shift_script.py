#!/usr/bin/env python3
"""Shift a harness input script in time (stdlib only).

usage: shift_script.py IN OUT --by N

Adds N (may be negative) to the frame of every "until F" command; every other
command is relative to the current frame and is copied unchanged, so the whole
script moves by N frames. Used to replay the scripts in ../input, which are
timed on a retail-BIOS boot (cartridge entry at harness frame 271), from
another start: --skip-bios enters the cartridge at frame 1 (N = -270), and the
Cult-of-GBA BIOS's own boot reaches it at frame 6 in mGBA 0.10.5 (N = -265).
See docs/research/open-bios-ab.md.

Fails if a shifted "until" would land before frame 1. The input scripts hold no
game data, and neither does the output, so OUT may be any path.
"""
import argparse
import re
import sys

UNTIL = re.compile(r"^(\s*until\s+)(\d+)(.*)$")


def shift(lines, by):
    out = []
    for no, line in enumerate(lines, 1):
        m = UNTIL.match(line)
        if m:
            frame = int(m.group(2)) + by
            if frame < 1:
                sys.exit(f"line {no}: 'until {m.group(2)}' shifted by {by} is before frame 1")
            line = f"{m.group(1)}{frame}{m.group(3)}\n"
        out.append(line)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("inp")
    ap.add_argument("out")
    ap.add_argument("--by", type=int, required=True)
    a = ap.parse_args()
    with open(a.inp) as f:
        lines = f.readlines()
    shifted = shift(lines, a.by)
    with open(a.out, "w") as f:
        f.write(f"# Generated by shift_script.py from {a.inp.split('/')[-1]}, 'until' frames shifted by {a.by}\n")
        f.writelines(shifted)


if __name__ == "__main__":
    main()
